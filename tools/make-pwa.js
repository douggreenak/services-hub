// Generates the PWA files (manifest, service worker, registration script, PNG icons) for every app we control,
// from the per-app SVG icons in public/icons. Re-run after changing an icon:  node tools/make-pwa.js
// Needs playwright-core (PW_CORE) only to rasterise the SVGs to PNG.
const fs = require('fs'), path = require('path'), os = require('os');
const { chromium } = require(process.env.PW_CORE || path.join(os.homedir(), 'pwtest/node_modules/playwright-core'));
const H = os.homedir(), ICONS = path.join(__dirname, '..', 'public', 'icons');

// dest: where the app serves static files from. base: URL path the app lives under ('/' or '/brightsign/').
const APPS = [
  { key: 'hub', icon: 'hub', name: 'Services Hub', short: 'Hub', desc: 'Every web app on this machine, one sign-in.', color: '#006a6a', bg: '#f4fafa', dest: path.join(__dirname, '..', 'public'), base: '/', start: '/apps' },
  { key: 'fleet', icon: 'jellyfin-fleet', name: 'Jellyfin Fleet', short: 'Fleet', desc: 'Manage the Apple TV fleet.', color: '#4338ca', bg: '#f5f5ff', dest: path.join(H, 'apps/Jellyfin-Apple-TV/management-server/admin/public'), base: '/', start: '/' },
  { key: 'audio', icon: 'audio-flow', name: 'Audio Flow Console', short: 'Audio Flow', desc: 'Spotify, BrightSign and Sonos signage audio.', color: '#1f9d6b', bg: '#f1faf5', dest: path.join(H, 'signage-dashboard/public'), base: '/', start: '/' },
  { key: 'tvm', icon: 'tv-manager', name: 'TV Manager', short: 'TV Manager', desc: 'Control the TVs.', color: '#2563eb', bg: '#f3f6ff', dest: path.join(H, 'tv-adb-manager/web'), base: '/', start: '/' },
  { key: 'brightsign', icon: 'brightsign', name: 'BrightSign Status', short: 'BrightSign', desc: 'BrightSign media feed sync status.', color: '#e8590c', bg: '#fff6f0', dest: '/srv/brightsign', base: '/brightsign/', start: '/brightsign/status.html' },
];

const SW = v => `// Minimal service worker (generated by tools/make-pwa.js). Makes the app installable and shows a friendly page
// offline. It never caches pages, API responses or logins: everything real still comes from the network.
const V = 'pwa-${v}';
const OFFLINE = '<!doctype html><meta charset=utf-8><meta name=viewport content="width=device-width,initial-scale=1"><title>Offline</title>' +
  '<body style="font:16px system-ui,sans-serif;display:grid;place-items:center;min-height:90vh;text-align:center;color:#444"><div><h2>You are offline</h2><p>Reconnect to the network and reload.</p></div>';
self.addEventListener('install', () => self.skipWaiting());
self.addEventListener('activate', e => e.waitUntil(caches.keys().then(ks => Promise.all(ks.filter(k => k !== V).map(k => caches.delete(k)))).then(() => self.clients.claim())));
self.addEventListener('fetch', e => {
  const r = e.request, u = new URL(r.url);
  if (r.method !== 'GET' || u.origin !== location.origin) return;
  if (/^\\/(api|go|logout)(\\/|$)/.test(u.pathname)) return;                       // never touch sign-in or data
  if (r.mode === 'navigate') { e.respondWith(fetch(r, { cache: 'no-cache' }).catch(() => new Response(OFFLINE, { headers: { 'Content-Type': 'text/html' } }))); return; }
  if (/\\/(icon-[\\w-]+\\.png|apple-touch-icon\\.png)$/.test(u.pathname))            // app icons: cache-first
    e.respondWith(caches.open(V).then(c => c.match(r).then(h => h || fetch(r).then(n => { if (n.ok) c.put(r, n.clone()); return n; }))));
});
`;
const REG = `// Registers the service worker (generated by tools/make-pwa.js).
if ('serviceWorker' in navigator) {
  const sw = new URL('sw.js', document.currentScript ? document.currentScript.src : location.href);
  window.addEventListener('load', () => navigator.serviceWorker.register(sw.href, { scope: new URL('./', sw).pathname }).catch(() => {}));
}
`;
const manifest = a => ({
  id: a.base, name: a.name, short_name: a.short, description: a.desc, start_url: a.start, scope: a.base,
  display: 'standalone', orientation: 'any', theme_color: a.color, background_color: a.bg, categories: ['utilities'],
  icons: [
    { src: a.base + 'icon-192.png', sizes: '192x192', type: 'image/png', purpose: 'any' },
    { src: a.base + 'icon-512.png', sizes: '512x512', type: 'image/png', purpose: 'any' },
    { src: a.base + 'icon-maskable-512.png', sizes: '512x512', type: 'image/png', purpose: 'maskable' },
  ],
});

// Full-bleed square (for maskable / Apple icons): the glyph is shrunk into the safe zone on a solid colour.
function fullBleed(svg, color, scale) {
  const inner = svg.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '').replace(/<rect width="64" height="64"[^>]*\/>/, '');
  const defs = (inner.match(/<defs>[\s\S]*?<\/defs>/) || [''])[0], rest = inner.replace(defs, '');
  const bg = /fill="url\(#g\)"/.test(svg) ? 'url(#g)' : color;
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64">${defs}<rect width="64" height="64" fill="${bg}"/><g transform="translate(32 32) scale(${scale}) translate(-32 -32)">${rest}</g></svg>`;
}

(async () => {
  const b = await chromium.launch(), page = await b.newPage();
  const png = async (svg, size, file, opaque) => {
    await page.setViewportSize({ width: size, height: size });
    await page.setContent(`<body style="margin:0;background:transparent"><img src="data:image/svg+xml;base64,${Buffer.from(svg).toString('base64')}" width="${size}" height="${size}" style="display:block">`);
    await page.waitForFunction(() => document.images[0].complete);
    fs.writeFileSync(file, await page.screenshot({ omitBackground: !opaque, type: 'png' }));
  };
  for (const a of APPS) {
    const svg = fs.readFileSync(path.join(ICONS, a.icon + '.svg'), 'utf8');
    fs.mkdirSync(a.dest, { recursive: true });
    await png(svg, 192, path.join(a.dest, 'icon-192.png'));
    await png(svg, 512, path.join(a.dest, 'icon-512.png'));
    await png(fullBleed(svg, a.color, 0.62), 512, path.join(a.dest, 'icon-maskable-512.png'), true);
    await png(fullBleed(svg, a.color, 0.8), 180, path.join(a.dest, 'apple-touch-icon.png'), true);
    fs.writeFileSync(path.join(a.dest, 'manifest.json'), JSON.stringify(manifest(a), null, 2) + '\n');
    fs.writeFileSync(path.join(a.dest, 'sw.js'), SW('v2'));
    fs.writeFileSync(path.join(a.dest, 'pwa.js'), REG);
    console.log('wrote PWA files for', a.name, '->', a.dest);
  }
  await b.close();
})();
